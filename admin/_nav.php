<?php
/**
 * نوارِ بخش‌های پنل مدیریت.
 *
 * ⛔ همه‌ی صفحه‌های `admin/` همین را include می‌کنند، پس فهرستِ بخش‌ها
 *    **یک جا** تعریف می‌شود. با کپی کردنش در هر صفحه، اضافه شدنِ یک
 *    بخشِ تازه یعنی چند جا یادت برود و کاربر بخشی را ببیند که از صفحه‌ی
 *    بغلی نمی‌بیند.
 *
 * ⚠ صفحه‌ای که هنوز روی دیسک نیست رندر نمی‌شود؛ وگرنه لینکش به ۴۰۴ِ
 *   خامِ nginx می‌رفت (همان درسِ `Auth::requireLogin()`).
 *
 * ⛔ نگهبانِ «مستقیم صدا زده نشو» — همان که `includes/due_tab_*.php`
 *    دارند، و اینجا جا مانده بود. دلیلش این است که سایتِ nginx فقط
 *    `/deploy/`, `/tests/`, `/config/` و `/includes/` را می‌بندد؛
 *    **`/admin/` را نمی‌بندد** (صفحه‌های واقعیِ مدیر آنجایند). پس
 *    `https://…/admin/_nav.php` از بیرون قابل باز کردن بود و برای هر
 *    کسی — حتی واردنشده — **خطای ۵۰۰** می‌داد، چون این فایل به تنهایی
 *    نه `Auth` را دارد نه `APP_BASE_PATH` را.
 *    با تستِ رندرِ صفحه‌ها پیدا شد، نه با نگاه.
 */
if (!defined('APP_BASE_PATH')) {
    http_response_code(404);
    exit;
}

/**
 * ⛔ هر بخش **توانایی**ِ لازمش را کنارِ خودش دارد، نه یک `if` پراکنده.
 *
 * **خواسته‌ی مالکِ نصب:** «امکان اضافه کردن ادمین با دسترسی محدود
 * مثلاً پشتیبانی». با یک نوارِ ثابت و چند `if` در صفحه‌های مختلف،
 * اولین بخشی که یادمان برود یعنی «پشتیبان» چیزی را می‌بیند که نباید.
 *
 * ⛔ و پیش‌فرض عمداً `'admin'` است — سمتِ **بسته**. بخشِ تازه‌ای که فردا
 *    بدونِ فکر اضافه شود مدیر-فقط می‌ماند؛ اگر پیش‌فرض `'support'`
 *    بود، هر صفحه‌ی تازه‌ی مدیر **بی‌صدا** برای پشتیبان باز می‌شد.
 */
$__adminTabs = [
    'users.php'      => ['کاربران', 'admin'],
    'access.php'     => ['ورود و پیامک', 'admin'],
    'categories.php' => ['دسته‌بندی‌ها', 'admin'],
    // ⚠ جای این قلم **زیرِ دسته‌بندی‌ها**ست، به خواسته‌ی صریحِ مالکِ
    //   نصب. ترتیبِ این آرایه همان ترتیبی است که روی نوار دیده می‌شود،
    //   و شیتِ مدیریت در `includes/footer.php` هم باید با آن بخواند —
    //   وگرنه کاربر روی گوشی و روی دسکتاپ دو ترتیبِ متفاوت می‌بیند.
    'billing.php'    => ['اشتراک و پرداخت', 'admin'],
    'store-billing.php' => ['اشتراکِ فروشگاه‌ها', 'admin'],
    'insights.php'   => ['آمار استفاده', 'admin'],
    'support.php'    => ['پشتیبانی', 'support'],
    'errors.php'     => ['خطاها', 'admin'],
    'store-share.php' => ['سهامداران فروشگاه', 'admin'],
    'rates.php'      => ['نرخ ارز و طلا', 'admin'],
];
$__here = basename($_SERVER['SCRIPT_NAME'] ?? '');

/**
 * ⛔ اطلاع‌رسانی، نه یک فهرستِ منتظرِ نگاه.
 *
 * **خواسته‌ی مالکِ نصب:** «توی بخش مدیریت اطلاع‌رسانی بشه». تا امروز
 * خطاها یک کارت در **تهِ** `admin/insights.php` بودند: تا کسی آن صفحه
 * را باز نمی‌کرد و تا پایین نمی‌رفت، هیچ‌جا نمی‌گفت چیزی خراب است.
 * حالا عددِ خطای **باز** روی خودِ نوارِ مدیر است، پس در هر شش صفحه
 * دیده می‌شود.
 *
 * ⚠ **هزینه‌اش یک کوئری روی هر صفحه‌ی `admin/` است و نوشته می‌ماند**
 *   (یک `COUNT` روی ایندکسِ `idx_open`؛ بودجه‌ی پنج صفحه در
 *   `test_query_budget` یکی بالا رفت). سنجشِ وجودِ ستون از نقشه‌ی
 *   کش‌شده‌ی ساختار می‌آید، پس کوئریِ دوم اضافه نمی‌کند.
 *
 * ⚠ و **با صفر اصلاً رندر نمی‌شود** — همان قاعده‌ی نقطه‌های اسلایدرِ
 *   خانه و نوارِ صفحه‌بندی: نشانِ «۰ خطا» چیزی نمی‌گوید و فقط آدم را
 *   عادت می‌دهد نگاهش نکند، و آن‌وقت «۳ خطا» هم دیده نمی‌شود.
 */
$__errOpen = Auth::isAdmin() ? AppErrors::openCount() : 0;

/**
 * ⛔ و همان استدلال برای تیکتِ منتظرِ پاسخ.
 *
 * تیکتی که مدیر ندیده باشد از خطای برنامه بدتر است: پشتِ آن یک آدم
 * نشسته و منتظر است. نشان اینجاست تا در هر شش صفحه‌ی `admin/` دیده
 * شود، نه فقط وقتی کسی صفحه‌ی پشتیبانی را باز کند.
 *
 * ⚠ **هزینه‌اش یک `COUNT` روی هر صفحه‌ی `admin/` است و نوشته می‌ماند**
 *   (روی ایندکسِ `idx_tk_wait`). بودجه‌ی صفحه‌های مدیر در
 *   `test_query_budget` همان‌قدر بالا رفت.
 *
 * ⚠ و **با صفر رندر نمی‌شود** — همان قاعده‌ی نشانِ خطاها: نشانِ «۰»
 *   فقط آدم را عادت می‌دهد نگاهش نکند.
 */
require_once __DIR__ . '/../includes/support.php';
$__supWait = Auth::can('support') ? Support::adminWaiting() : 0;
?>
<nav class="admin-tabs" aria-label="بخش‌های مدیریت">
    <?php foreach ($__adminTabs as $__file => [$__label, $__cap]): ?>
        <?php if (!is_file(__DIR__ . '/' . $__file)) { continue; } ?>
        <?php if (!Auth::can($__cap)) { continue; } ?>
        <a href="<?= APP_BASE_PATH ?>/admin/<?= h($__file) ?>"
           class="admin-tab <?= $__here === $__file ? 'is-active' : '' ?>"
           <?= $__here === $__file ? 'aria-current="page"' : '' ?>><?= h($__label) ?><?php
            if ($__file === 'errors.php' && $__errOpen > 0): ?><span
                class="admin-tab-badge ltr-num"><?= h(toPersianDigits((string)$__errOpen)) ?></span><?php
            endif;
            if ($__file === 'support.php' && $__supWait > 0): ?><span
                class="admin-tab-badge ltr-num"><?= h(toPersianDigits((string)$__supWait)) ?></span><?php
            endif; ?></a>
    <?php endforeach; ?>
</nav>
