    /** @return array{0:string, 1:list<string>}|null */
    public static function topic(string $page): ?array
    {
        return self::TOPICS[$page] ?? null;
    }

    /** دکمه‌ی «؟» برای نوارِ بالا — بی‌جاوااسکریپت. */
    public static function button(string $page): string
    {
        $t = self::topic($page);
        if ($t === null) { return ''; }
        $li = '';
        foreach ($t[1] as $p) { $li .= '<li>' . htmlspecialchars($p, ENT_QUOTES, 'UTF-8') . '</li>'; }
        return '<details class="st-dd st-help"><summary class="st-icon-btn" aria-label="راهنمای این صفحه" title="راهنمای این صفحه">؟</summary>'
             . '<div class="st-dd-menu st-help-menu" role="note"><b>' . htmlspecialchars($t[0], ENT_QUOTES, 'UTF-8') . '</b><ul>' . $li . '</ul>'
             . '<a href="' . htmlspecialchars(Biz::url('help.php') . '#' . pathinfo($page, PATHINFO_FILENAME), ENT_QUOTES, 'UTF-8') . '">همه‌ی راهنما</a></div></details>';
    }
